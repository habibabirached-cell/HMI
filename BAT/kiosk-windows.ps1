# Shared Maingear kiosk window registry + focus helpers (DCS :3003 / Vernova :5173).
# Lives in BAT/ — dot-sourced by focus-kiosk-window.ps1 and repo-root open-chrome-window.ps1.

Set-StrictMode -Version Latest

$script:KioskRegistryPath = Join-Path $PSScriptRoot "kiosk-windows.json"

function Write-WaitMsg {
    param([string] $Message)
    Write-Host $Message
}

if (-not ("KioskWindowApi" -as [type])) {
    Add-Type @"
using System;
using System.Runtime.InteropServices;
using System.Text;
using System.Collections.Generic;

public static class KioskWindowApi {
    public delegate bool EnumWindowsProc(IntPtr hWnd, IntPtr lParam);

    [DllImport("user32.dll")]
    public static extern bool IsWindow(IntPtr hWnd);

    [DllImport("user32.dll")]
    public static extern bool SetForegroundWindow(IntPtr hWnd);

    [DllImport("user32.dll")]
    public static extern bool ShowWindow(IntPtr hWnd, int nCmdShow);

    [DllImport("user32.dll")]
    public static extern bool GetWindowRect(IntPtr hWnd, out RECT lpRect);

    [DllImport("user32.dll")]
    public static extern bool EnumWindows(EnumWindowsProc lpEnumFunc, IntPtr lParam);

    [DllImport("user32.dll")]
    public static extern bool IsWindowVisible(IntPtr hWnd);

    [DllImport("user32.dll")]
    public static extern uint GetWindowThreadProcessId(IntPtr hWnd, out uint processId);

    [DllImport("user32.dll")]
    public static extern IntPtr GetForegroundWindow();

    [DllImport("user32.dll")]
    public static extern bool AttachThreadInput(uint idAttach, uint idAttachTo, bool fAttach);

    [DllImport("user32.dll")]
    public static extern bool SetWindowPos(IntPtr hWnd, IntPtr hWndInsertAfter, int X, int Y, int cx, int cy, uint uFlags);

    [DllImport("user32.dll")]
    public static extern bool BringWindowToTop(IntPtr hWnd);

    [DllImport("user32.dll")]
    public static extern void SwitchToThisWindow(IntPtr hWnd, bool fAltTab);

    [DllImport("user32.dll")]
    public static extern bool IsIconic(IntPtr hWnd);

    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    public static extern int GetWindowText(IntPtr hWnd, StringBuilder lpString, int nMaxCount);

    [StructLayout(LayoutKind.Sequential)]
    public struct RECT {
        public int Left;
        public int Top;
        public int Right;
        public int Bottom;
    }

    public static string GetWindowTitle(IntPtr hWnd) {
        var sb = new StringBuilder(512);
        GetWindowText(hWnd, sb, sb.Capacity);
        return sb.ToString();
    }

    public static List<IntPtr> FindVisibleChromeWindows() {
        var handles = new List<IntPtr>();
        EnumWindows((hWnd, _) => {
            if (!IsWindowVisible(hWnd)) return true;
            uint pid;
            GetWindowThreadProcessId(hWnd, out pid);
            try {
                var proc = System.Diagnostics.Process.GetProcessById((int)pid);
                if (!string.Equals(proc.ProcessName, "chrome", StringComparison.OrdinalIgnoreCase)) {
                    return true;
                }
            } catch {
                return true;
            }
            var title = GetWindowTitle(hWnd);
            if (title != null && title.Length > 0) {
                handles.Add(hWnd);
            }
            return true;
        }, IntPtr.Zero);
        return handles;
    }
}
"@
}

function Get-KioskRegistryPath {
    return $script:KioskRegistryPath
}

function Get-KioskChromeProfileDir {
    param(
        [Parameter(Mandatory = $true)]
        [ValidateSet("Dcs", "Vernova")]
        [string] $Target
    )

    $name = $Target.ToLowerInvariant()
    return Join-Path $env:LOCALAPPDATA "DataCenterSmartPower\chrome-kiosk-$name"
}

# Kiosk profiles are separate from the default Chrome profile (open-hmi uses default → gray bar).
# Each kiosk profile can cache Chrome's autogenerated theme from page colors (DCS teal → cyan bar).
# Force the window frame color on every launch via Chrome's native switch (r,g,b 0–255).
function Get-KioskChromeThemeArg {
    param(
        [Parameter(Mandatory = $true)]
        [ValidateSet("Dcs", "Vernova")]
        [string] $Target
    )

    switch ($Target) {
        "Dcs"     { return "--install-autogenerated-theme=26,26,26" }   # #1a1a1a app-header gray
        "Vernova" { return "--install-autogenerated-theme=0,71,69" }    # #004745 Vernova green
    }
}

function Read-KioskWindowRegistry {
    $path = Get-KioskRegistryPath
    if (-not (Test-Path -LiteralPath $path)) {
        return [PSCustomObject]@{}
    }

    try {
        return Get-Content -LiteralPath $path -Raw | ConvertFrom-Json
    } catch {
        Write-Warning "Could not read kiosk registry at $path"
        return [PSCustomObject]@{}
    }
}

function Write-KioskWindowRegistryEntry {
    param(
        [Parameter(Mandatory = $true)]
        [ValidateSet("Dcs", "Vernova")]
        [string] $Target,

        [Parameter(Mandatory = $true)]
        [IntPtr] $Handle,

        [Parameter(Mandatory = $true)]
        [string] $Url
    )

    $path = Get-KioskRegistryPath
    $key = $Target.ToLowerInvariant()
    $existing = @{}
    if (Test-Path -LiteralPath $path) {
        try {
            $raw = Get-Content -LiteralPath $path -Raw | ConvertFrom-Json
            foreach ($prop in $raw.PSObject.Properties) {
                $existing[$prop.Name] = $prop.Value
            }
        } catch {
            $existing = @{}
        }
    }

    $existing[$key] = [ordered]@{
        hwnd      = $Handle.ToInt64()
        url       = $Url
        profile   = (Get-KioskChromeProfileDir -Target $Target)
        updatedAt = (Get-Date).ToString("o")
    }

    $payload = [ordered]@{}
    foreach ($entryKey in @("dcs", "vernova")) {
        if ($existing.ContainsKey($entryKey)) {
            $payload[$entryKey] = $existing[$entryKey]
        }
    }

    ($payload | ConvertTo-Json -Depth 4) | Set-Content -LiteralPath $path -Encoding UTF8
    Write-Host "Saved kiosk window '$Target' (hwnd=$Handle) -> $path"
}

function Test-KioskWindowHandle {
    param([IntPtr] $Handle)
    return ($Handle -ne [IntPtr]::Zero) -and [KioskWindowApi]::IsWindow($Handle)
}

function Get-KioskWindowArea {
    param([IntPtr] $Handle)

    $rect = New-Object KioskWindowApi+RECT
    if (-not [KioskWindowApi]::GetWindowRect($Handle, [ref]$rect)) {
        return 0
    }
    return [Math]::Max(0, $rect.Right - $rect.Left) * [Math]::Max(0, $rect.Bottom - $rect.Top)
}

function Find-KioskChromeWindow {
    param(
        [Parameter(Mandatory = $true)]
        [ValidateSet("Dcs", "Vernova")]
        [string] $Target
    )

    $registry = Read-KioskWindowRegistry
    $key = $Target.ToLowerInvariant()
    $entry = $registry.$key

    $bestHandle = [IntPtr]::Zero
    $bestArea = 0
    $largestHandle = [IntPtr]::Zero
    $largestArea = 0
    foreach ($hwnd in [KioskWindowApi]::FindVisibleChromeWindows()) {
        $area = Get-KioskWindowArea -Handle $hwnd
        if ($area -gt $largestArea) {
            $largestHandle = $hwnd
            $largestArea = $area
        }
        if ($area -le $bestArea) { continue }

        $title = [KioskWindowApi]::GetWindowTitle($hwnd)
        if (-not $title) { continue }

        $titleMatches = $false
        if ($Target -eq "Dcs") {
            $titleMatches = ($title -match "Data Center|ACDC|Configurator|HD_Aero|P2R|localhost:3003") -or ($title -match "3003")
        } else {
            $titleMatches = ($title -match "Spark|Vernova|VERNOVA|localhost:5173") -or ($title -match "5173")
        }

        if ($titleMatches -or $area -gt 3000000) {
            $bestHandle = $hwnd
            $bestArea = $area
        }
    }

    if ($bestHandle -ne [IntPtr]::Zero) {
        return $bestHandle
    }

    return $largestHandle
}

function Get-KioskSiblingWindowHandle {
    param(
        [Parameter(Mandatory = $true)]
        [ValidateSet("Dcs", "Vernova")]
        [string] $Target
    )

    $otherKey = if ($Target -eq "Dcs") { "vernova" } else { "dcs" }
    $registry = Read-KioskWindowRegistry
    $entry = $registry.$otherKey
    if (-not ($entry -and $entry.hwnd)) {
        return [IntPtr]::Zero
    }

    $sibling = [IntPtr]::new([int64]$entry.hwnd)
    if (Test-KioskWindowHandle -Handle $sibling) {
        return $sibling
    }
    return [IntPtr]::Zero
}

function Send-KioskWindowToBack {
    param([Parameter(Mandatory = $true)] [IntPtr] $Handle)

    if (-not (Test-KioskWindowHandle -Handle $Handle)) { return }

    $HWND_BOTTOM = [IntPtr]::new(1)
    $flags = [uint32]0x0003 -bor 0x0010  # SWP_NOMOVE | SWP_NOSIZE | SWP_NOACTIVATE
    [void][KioskWindowApi]::SetWindowPos($Handle, $HWND_BOTTOM, 0, 0, 0, 0, $flags)
}

function Activate-KioskWindow {
    param(
        [Parameter(Mandatory = $true)]
        [IntPtr] $Handle,

        [IntPtr] $SendOtherToBack = [IntPtr]::Zero
    )

    if (-not (Test-KioskWindowHandle -Handle $Handle)) {
        throw "Invalid window handle $Handle"
    }

    if ([KioskWindowApi]::IsIconic($Handle)) {
        [void][KioskWindowApi]::ShowWindow($Handle, 9)
    }

    if ($SendOtherToBack -ne [IntPtr]::Zero) {
        Send-KioskWindowToBack -Handle $SendOtherToBack
    }

    $HWND_TOPMOST = [IntPtr]::new(-1)
    $HWND_NOTOPMOST = [IntPtr]::new(-2)
    $swpShow = [uint32]0x0043  # SWP_NOMOVE | SWP_NOSIZE | SWP_SHOWWINDOW

    [void][KioskWindowApi]::SetWindowPos($Handle, $HWND_TOPMOST, 0, 0, 0, 0, $swpShow)
    [void][KioskWindowApi]::SetWindowPos($Handle, $HWND_NOTOPMOST, 0, 0, 0, 0, $swpShow)
    [void][KioskWindowApi]::BringWindowToTop($Handle)

    $foreground = [KioskWindowApi]::GetForegroundWindow()
    $fgPid = [uint32]0
    $fgThread = [KioskWindowApi]::GetWindowThreadProcessId($foreground, [ref]$fgPid)
    $targetPid = [uint32]0
    $targetThread = [KioskWindowApi]::GetWindowThreadProcessId($Handle, [ref]$targetPid)

    if ($fgThread -ne 0 -and $targetThread -ne 0 -and $fgThread -ne $targetThread) {
        [void][KioskWindowApi]::AttachThreadInput($fgThread, $targetThread, $true)
        [void][KioskWindowApi]::SetForegroundWindow($Handle)
        [void][KioskWindowApi]::AttachThreadInput($fgThread, $targetThread, $false)
    } else {
        [void][KioskWindowApi]::SetForegroundWindow($Handle)
    }

    [void][KioskWindowApi]::SetForegroundWindow($Handle)
}

function Show-KioskWindow {
    param(
        [Parameter(Mandatory = $true)]
        [IntPtr] $Handle,

        [switch] $NoActivate
    )

    if (-not (Test-KioskWindowHandle -Handle $Handle)) {
        throw "Invalid window handle $Handle"
    }

    if ($NoActivate) {
        [void][KioskWindowApi]::ShowWindow($Handle, 4)
        return
    }

    Activate-KioskWindow -Handle $Handle
}

function Focus-KioskWindow {
    param(
        [Parameter(Mandatory = $true)]
        [ValidateSet("Dcs", "Vernova")]
        [string] $Target
    )

    $registry = Read-KioskWindowRegistry
    $key = $Target.ToLowerInvariant()
    $entry = $registry.$key
    $handle = [IntPtr]::Zero

    if ($entry -and $entry.hwnd) {
        $candidate = [IntPtr]::new([int64]$entry.hwnd)
        if (Test-KioskWindowHandle -Handle $candidate) {
            $handle = $candidate
        }
    }

    if ($handle -eq [IntPtr]::Zero) {
        Write-Warning "Saved handle for '$Target' missing or stale; scanning Chrome windows..."
        $handle = Find-KioskChromeWindow -Target $Target
    }

    if ($handle -eq [IntPtr]::Zero) {
        throw "Could not find a Chrome kiosk window for '$Target'. Run BAT\z_genesis.start.bat first."
    }

    $sibling = Get-KioskSiblingWindowHandle -Target $Target
    Activate-KioskWindow -Handle $handle -SendOtherToBack $sibling

    $url = $(if ($entry -and $entry.url) { [string]$entry.url } else { if ($Target -eq "Dcs") { "http://localhost:3003" } else { "http://localhost:5173" } })
    $needsSave = (-not $entry) -or (-not $entry.hwnd) -or ([int64]$entry.hwnd -ne $handle.ToInt64())
    if ($needsSave) {
        Write-KioskWindowRegistryEntry -Target $Target -Handle $handle -Url $url
    }
    Write-Host "Focused kiosk window: $Target (hwnd=$handle)"
}

function Wait-ForTcpPort {
    param(
        [Parameter(Mandatory = $true)]
        [int] $Port,

        [int] $TimeoutSeconds = 180,

        [string] $Label = "port $Port",

        [int] $ProgressIntervalSeconds = 15
    )

    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    $started = Get-Date
    $lastProgressBucket = 0

    Write-WaitMsg ""
    Write-WaitMsg ('Waiting for {0} on 127.0.0.1:{1} (timeout {2}s) ...' -f $Label, $Port, $TimeoutSeconds)
    if ($Port -eq 5173) {
        Write-WaitMsg '  Vernova npm run dev can take 1-3 minutes on a cold start — please wait.'
    }

    while ((Get-Date) -lt $deadline) {
        $elapsedSeconds = [int][math]::Floor(((Get-Date) - $started).TotalSeconds)
        if ($ProgressIntervalSeconds -gt 0 -and $elapsedSeconds -ge $ProgressIntervalSeconds) {
            $bucket = [int][math]::Floor($elapsedSeconds / $ProgressIntervalSeconds) * $ProgressIntervalSeconds
            if ($bucket -gt $lastProgressBucket) {
                Write-WaitMsg ('  ... still waiting for {0} ({1}s elapsed, {2}s max)' -f $Label, $bucket, $TimeoutSeconds)
                $lastProgressBucket = $bucket
            }
        }

        try {
            $client = New-Object System.Net.Sockets.TcpClient
            $async = $client.BeginConnect('127.0.0.1', $Port, $null, $null)
            $ok = $async.AsyncWaitHandle.WaitOne(500)
            if ($ok -and $client.Connected) {
                $client.Close()
                Write-WaitMsg ('{0} is ready after {1}s.' -f $Label, $elapsedSeconds)
                return
            }
            $client.Close()
        } catch {
            # keep polling
        }
        Start-Sleep -Milliseconds 500
    }

    throw ('Timed out waiting for {0} on port {1} after {2}s' -f $Label, $Port, $TimeoutSeconds)
}
